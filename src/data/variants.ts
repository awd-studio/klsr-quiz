import type { QuestionId, Variant } from './types.ts';

/*
 * Альтернативні формати питань для режиму «Вибір варіанту».
 *
 * Правила:
 * - Правильна відповідь у форматах term / mcq / multi / order береться з
 *   `Question.a` (дослівно з файлу). Тут — лише формулювання та неправильні варіанти.
 * - `tf.statement` — частина речення після «Чи правильне твердження, що …».
 *   Кожне твердження однозначно випливає з відповіді на питання, до якого воно прив’язане;
 *   після відповіді користувач бачить це питання і відповідь з файлу.
 * - `exam: true` — формат/формулювання розпізнано на фото залікових білетів.
 */

const MOTIVATION = ['Внутрішня мотивація', 'Зовнішня мотивація', 'Індивідуальна мотивація', 'Групова мотивація'];
const others = (all: readonly string[], term: string): [string, string, string] => {
  const rest = all.filter((t) => t !== term);
  if (rest.length !== 3) throw new Error(`Expected 3 other terms for ${term}`);
  return [rest[0]!, rest[1]!, rest[2]!];
};

const tf = (statement: string, correct: boolean, exam?: true): Variant =>
  exam ? { kind: 'tf', statement, correct, exam } : { kind: 'tf', statement, correct };
const term = (t: string, o: readonly [string, string, string], exam?: true): Variant =>
  exam ? { kind: 'term', term: t, others: o, exam } : { kind: 'term', term: t, others: o };

